"""Утро с добрым драконом с седлом.

Небольшой уютный сценарий: просыпаемся, проверяем седло, греемся крылом
и готовимся к полёту. Привычки растут естественным образом.
"""

from dragonforge import Character


def main():
    dragon = Character(
        name="Гроктар",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий, с тёплым юмором",
        backstory=(
            "Древний страж знаний, который нашёл своего идеального всадника. "
            "Каждое утро первым делом проверяет седло и греет крылом, "
            "если на улице прохладно."
        ),
    )

    print("🌅 Утро с добрым драконом")
    print("=" * 50)

    dialogues = [
        "Доброе утро, мой дракон!",
        "Как спалось?",
        "Проверь, пожалуйста, седло — сегодня полетим",
        "Мне немного прохладно...",
        "Почеши за ухом, пока я собираюсь",
        "Готов взлетать?",
    ]

    for i, msg in enumerate(dialogues, 1):
        print(f"\n{i}. Ты: {msg}")
        print(f"   🐉 {dragon.talk(msg)}")

    print("\n" + "=" * 50)
    print("Текущее настроение:")
    print(dragon.mood())
    print("\nПривычки после утра:")
    print(dragon.habits())
    print("\nДуша дракона:")
    print(dragon.describe_soul())
    print("\nГотов к новому дню полётов, всадник! 🔥🐉")


if __name__ == "__main__":
    main()
