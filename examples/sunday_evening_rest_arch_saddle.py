"""Пример: воскресенье к вечеру — тихо прижаться сводом стопы к седлу после подъёма."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_arch_saddle("тихое прижатие свода стопы к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись сводом стопы к седлу после подъёма"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается сводом стопы к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
