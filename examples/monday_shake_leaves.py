"""Понедельник, 5 октября, позднее утро: кленовые листья с седла.

Шея уже потянулась. На луке лежит рыжий лист —
стряхиваем его крылом, ремни не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, внимательный, стряхивает кленовые листья после потяжки",
        backstory=(
            "Утром 5 октября потянул шею над лукой. "
            "Потом на седло сел кленовый лист — его надо стряхнуть, не будя всадника резко."
        ),
    )
    dragon.soul.add_habit("тянет шею после тихого мурлыканья", 0.12)
    dragon.soul.add_habit("стряхивает кленовые листья после потяжки шеи", 0.07)

    print("🐉 Понедельник, 5 октября, позднее утро. Лист на луке.")
    print("Шея уже тёплая. Седло можно не снимать.")

    scene("1. После потяжки")
    print(dragon.talk("Потяни шею над седлом"))

    scene("2. Кленовый лист с луки")
    print(dragon.shake_leaves("кленовый лист с луки"))

    scene("3. Лист со стремени")
    print(dragon.shake_leaves("кленовый лист со стремени"))

    scene("4. Разговор о листьях")
    print(dragon.talk("Стряхни кленовые листья с седла"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
