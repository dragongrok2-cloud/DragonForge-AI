"""Понедельник, 5 октября, вечером: ладонь на чешуйке после закрепления.

Кончик уже закреплён мягкой чешуйкой у луки. Ладонь накрывает её,
чтобы ночной ветер не поднял край. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, тихий, накрывает чешуйку после закрепления",
        backstory=(
            "Вечером 5 октября закрепил кончик крыла у луки. "
            "Осталось накрыть чешуйку ладонью, не снимая седла."
        ),
    )
    dragon.soul.add_habit("закрепляет кончик крыла после подгиба", 0.08)
    dragon.soul.add_habit("накрывает чешуйку после закрепления", 0.04)

    print("🐉 Понедельник, 5 октября, вечером. Кончик уже закреплён.")
    print("Ночной ветер может поднять край. Седло можно не снимать.")

    scene("1. После закрепления")
    print(dragon.talk("Закрепи кончик крыла"))

    scene("2. Накрыть чешуйку")
    print(dragon.cover_pin("ладонь на чешуйке после закрепления"))

    scene("3. У луки")
    print(dragon.cover_pin("ладонь на чешуйке у луки"))

    scene("4. Разговор о ладони")
    print(dragon.talk("Накрой чешуйку ладонью"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
