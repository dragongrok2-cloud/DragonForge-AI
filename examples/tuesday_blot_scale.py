"""Вторник, 6 октября, утром: роса с чешуйки после ладони.

Ладонь уже поднята с чешуйки у луки. Край крыла промокает каплю,
чтобы перчатка не липла. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, тихий, промокает чешуйку после ладони",
        backstory=(
            "Утром 6 октября поднял ладонь с чешуйки у луки. "
            "Осталось промокнуть росу, не снимая седла."
        ),
    )
    dragon.soul.add_habit("поднимает ладонь после нажатия", 0.08)
    dragon.soul.add_habit("промокает чешуйку после ладони", 0.04)

    print("🐉 Вторник, 6 октября, утром. Ладонь уже с чешуйки.")
    print("Капля росы ещё на крае. Седло можно не снимать.")

    scene("1. После подъёма ладони")
    print(dragon.talk("Подними ладонь утром"))

    scene("2. Роса с чешуйки")
    print(dragon.blot_scale("роса с чешуйки после ладони"))

    scene("3. У луки")
    print(dragon.blot_scale("роса с чешуйки у луки"))

    scene("4. Разговор о капле")
    print(dragon.talk("Промокни чешуйку после ладони"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
