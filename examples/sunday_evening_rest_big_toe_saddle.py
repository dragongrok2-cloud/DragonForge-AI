"""Пример: воскресенье к вечеру — тихо прижаться большим пальцем стопы к седлу после подушечки."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_big_toe_saddle("тихое прижатие большого пальца стопы к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись большим пальцем стопы к седлу после подушечки"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается большим пальцем стопы к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
