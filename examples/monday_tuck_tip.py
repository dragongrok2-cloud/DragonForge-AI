"""Понедельник, 5 октября, после полудня: кончик крыла после сушки.

Край крыла уже прошёл по сухой траве. Кончик подгибается к луке,
чтобы не ловить ветер. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, аккуратный, подгибает кончик после сушки",
        backstory=(
            "К вечеру 5 октября просушил край крыла о траву у стремени. "
            "Кончик ещё свободен — его можно подогнуть к луке, не снимая седла."
        ),
    )
    dragon.soul.add_habit("сушит край крыла после сока", 0.10)
    dragon.soul.add_habit("подгибает кончик крыла после сушки", 0.05)

    print("🐉 Понедельник, 5 октября, после полудня. Край крыла сухой.")
    print("Кончик ещё ловит ветер. Седло можно не снимать.")

    scene("1. После сушки")
    print(dragon.talk("Высуши крыло после сока"))

    scene("2. Кончик крыла")
    print(dragon.tuck_tip("кончик крыла после сушки"))

    scene("3. К луке")
    print(dragon.tuck_tip("кончик крыла к луке"))

    scene("4. Разговор о кончике")
    print(dragon.talk("Подогни кончик крыла"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
