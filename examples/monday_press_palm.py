"""Понедельник, 5 октября, вечером: ладонь один раз после накрытия.

Чешуйка уже накрыта ладонью у луки. Одно мягкое нажатие,
чтобы ночной ветер не поднял край. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, тихий, прижимает ладонь после накрытия",
        backstory=(
            "Вечером 5 октября накрыл чешуйку ладонью у луки. "
            "Осталось один раз мягко прижать, не снимая седла."
        ),
    )
    dragon.soul.add_habit("накрывает чешуйку после закрепления", 0.08)
    dragon.soul.add_habit("прижимает ладонь после накрытия", 0.04)

    print("🐉 Понедельник, 5 октября, вечером. Чешуйка уже под ладонью.")
    print("Ночной ветер может поднять край. Седло можно не снимать.")

    scene("1. После накрытия")
    print(dragon.talk("Накрой чешуйку ладонью"))

    scene("2. Мягкое нажатие")
    print(dragon.press_palm("мягкое нажатие после накрытия"))

    scene("3. У луки")
    print(dragon.press_palm("нажатие у луки"))

    scene("4. Разговор о нажатии")
    print(dragon.talk("Прижми ладонь один раз"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
