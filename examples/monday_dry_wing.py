"""Понедельник, 5 октября, к вечеру: край крыла после сока.

Лука уже сухая. Край крыла, которым сняли сок, проходит по сухой траве
у стремени. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, аккуратный, сушит крыло после сока",
        backstory=(
            "После полудня 5 октября снял яблочный сок с луки краем крыла. "
            "Перепонка ещё чуть липкая — её можно просушить о траву, не снимая седла."
        ),
    )
    dragon.soul.add_habit("вытирает сок с луки после яблока", 0.11)
    dragon.soul.add_habit("сушит край крыла после сока", 0.06)

    print("🐉 Понедельник, 5 октября, к вечеру. Лука сухая.")
    print("Край крыла ещё помнит сок. Седло можно не снимать.")

    scene("1. После сока")
    print(dragon.talk("Вытри сок с луки"))

    scene("2. Край крыла")
    print(dragon.dry_wing("край крыла после сока"))

    scene("3. Сухая трава")
    print(dragon.dry_wing("край крыла о сухую траву"))

    scene("4. Разговор о крыле")
    print(dragon.talk("Высуши крыло после сока"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
