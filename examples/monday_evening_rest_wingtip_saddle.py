"""Пример: понедельник к вечеру — тихо положить кончик крыла на седло после ладони."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_wingtip_saddle("тихое положение кончика крыла на седло под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Положи кончик крыла на седло после ладони"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо кладёт кончик крыла на седло под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
