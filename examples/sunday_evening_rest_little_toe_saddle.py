"""Пример: воскресенье к вечеру — тихо прижаться мизинцем стопы к седлу после большого пальца."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_little_toe_saddle("тихое прижатие мизинца стопы к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись мизинцем стопы к седлу после большого пальца"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается мизинцем стопы к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
