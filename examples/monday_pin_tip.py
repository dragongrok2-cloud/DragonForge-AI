"""Понедельник, 5 октября, к вечеру: кончик у луки после подгиба.

Кончик уже подогнут и не ловит ветер. Мягкая чешуйка закрепляет его
у луки, чтобы вечерний порыв не поднял край. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, аккуратный, закрепляет кончик после подгиба",
        backstory=(
            "К вечеру 5 октября подогнул кончик крыла к луке. "
            "Осталось прижать его мягкой чешуйкой, не снимая седла."
        ),
    )
    dragon.soul.add_habit("подгибает кончик крыла после сушки", 0.08)
    dragon.soul.add_habit("закрепляет кончик крыла после подгиба", 0.04)

    print("🐉 Понедельник, 5 октября, к вечеру. Кончик уже подогнут.")
    print("Ветер может подхватить край. Седло можно не снимать.")

    scene("1. После подгиба")
    print(dragon.talk("Подогни кончик крыла"))

    scene("2. Закрепить кончик")
    print(dragon.pin_tip("кончик у луки после подгиба"))

    scene("3. Под мягкой чешуйкой")
    print(dragon.pin_tip("кончик под мягкой чешуйкой"))

    scene("4. Разговор о закреплении")
    print(dragon.talk("Закрепи кончик крыла"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
