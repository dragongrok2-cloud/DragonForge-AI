"""Понедельник, 5 октября, к полудню: лука после листьев.

Листья уже стряхнуты. Луку разглаживаем крылом,
чтобы ладонь нашла сухое седло — ремни не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, внимательный, разглаживает луку после листьев",
        backstory=(
            "Утром 5 октября стряхнул кленовые листья с седла. "
            "К полудню лука ещё помнит рыжий край — её надо разгладить, не снимая ремней."
        ),
    )
    dragon.soul.add_habit("стряхивает кленовые листья после потяжки шеи", 0.11)
    dragon.soul.add_habit("разглаживает луку после кленовых листьев", 0.06)

    print("🐉 Понедельник, 5 октября, к полудню. Листья уже в стороне.")
    print("Лука ждёт ладонь. Седло можно не снимать.")

    scene("1. После листьев")
    print(dragon.talk("Стряхни кленовые листья с седла"))

    scene("2. Лука после листьев")
    print(dragon.smooth_pommel("лука после листьев"))

    scene("3. Лука над стременем")
    print(dragon.smooth_pommel("лука над стременем"))

    scene("4. Разговор о луке")
    print(dragon.talk("Разгладь луку после листьев"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
