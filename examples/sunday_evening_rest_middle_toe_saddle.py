"""Пример: воскресенье к вечеру — тихо прижаться средним пальцем стопы к седлу после мизинца."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_middle_toe_saddle("тихое прижатие среднего пальца стопы к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись средним пальцем стопы к седлу после мизинца"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается средним пальцем стопы к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
