"""Понедельник, 5 октября, в полдень: яблоко после луки.

Лука уже гладкая. Из седельной сумки достаём кислое яблоко,
делим пополам и не снимаем ремни.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, щедрый, делится яблоком после гладкой луки",
        backstory=(
            "К полудню 5 октября разгладил луку после кленовых листьев. "
            "В седельной сумке лежит кислое яблоко — его можно разделить, не снимая седла."
        ),
    )
    dragon.soul.add_habit("разглаживает луку после кленовых листьев", 0.11)
    dragon.soul.add_habit("делится яблоком после гладкой луки", 0.06)

    print("🐉 Понедельник, 5 октября, в полдень. Лука сухая.")
    print("Сумка тихо шуршит. Седло можно не снимать.")

    scene("1. После луки")
    print(dragon.talk("Разгладь луку после листьев"))

    scene("2. Яблоко из сумки")
    print(dragon.share_apple("кислое яблоко из седельной сумки"))

    scene("3. Половинка")
    print(dragon.share_apple("половинка яблока"))

    scene("4. Разговор о яблоке")
    print(dragon.talk("Поделись яблоком после луки"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
