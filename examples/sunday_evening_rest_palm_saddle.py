"""Пример: воскресенье к вечеру — тихо прижаться ладонью к седлу после запястья."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_palm_saddle("тихое прижатие ладони к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись ладонью к седлу после запястья"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается ладонью к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
