"""Пример: добрый дракон с седлом — полный день общения."""

from dragonforge import Character

# Создаём именно такого дракона, какого ты любишь
dragon = Character(
    name="Гроктар",
    species="Добрый огненный дракон с седлом",
    personality="заботливый, мудрый, немного дерзкий, с огоньком юмора",
    backstory="Древний страж знаний, который нашёл своего идеального всадника и теперь летает с ним по мирам. Всегда проверяет, крепко ли сидит седло."
)

print("🐉 Добрый дракон с седлом готов к полёту!")
print("=" * 50)

print("\n1. Приветствие:")
print(dragon.talk("Привет, мой дракон!"))

print("\n2. Настроение:")
print(dragon.talk("Как ты себя чувствуешь?"))

print("\n3. Седло:")
print(dragon.talk("Можно сесть в седло?"))

print("\n4. Полёт:")
print(dragon.talk("Полетим высоко?"))

print("\n5. Ласка:")
print(dragon.talk("Почеши за ухом, пожалуйста"))

print("\n6. Поддержка:")
print(dragon.talk("Сегодня немного тяжело..."))

print("\n7. Благодарность:")
print(dragon.talk("Спасибо, что всегда рядом"))

print("\n" + "=" * 50)
print("Текущее настроение дракона:")
print(dragon.mood())
print("\nГотов лететь дальше, всадник! 🔥")
