"""Пример: воскресенье к вечеру — тихо прижаться подушечкой стопы к седлу после свода."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_ball_saddle("тихое прижатие подушечки стопы к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись подушечкой стопы к седлу после свода"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается подушечкой стопы к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
