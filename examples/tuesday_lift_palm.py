"""Вторник, 6 октября, утром: ладонь с чешуйки после ночного нажатия.

Ночью ладонь один раз прижала чешуйку у луки. Утром её поднимают,
чтобы роса не приклеила край. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, тихий, поднимает ладонь после нажатия",
        backstory=(
            "Вечером 5 октября прижал ладонь к чешуйке у луки. "
            "Утром 6 октября поднимает её, не снимая седла."
        ),
    )
    dragon.soul.add_habit("прижимает ладонь после накрытия", 0.08)
    dragon.soul.add_habit("поднимает ладонь после нажатия", 0.04)

    print("🐉 Вторник, 6 октября, утром. Ночное нажатие уже сделано.")
    print("Роса может приклеить край. Седло можно не снимать.")

    scene("1. После нажатия")
    print(dragon.talk("Прижми ладонь один раз"))

    scene("2. Утренняя ладонь")
    print(dragon.lift_palm("ладонь после ночного нажатия"))

    scene("3. У луки")
    print(dragon.lift_palm("ладонь у луки"))

    scene("4. Разговор о подъёме")
    print(dragon.talk("Подними ладонь утром"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
