"""Пятница 2 октября, утро, полёт в седле перед выходными.

Второй день октября. На траве лёгкий иней, седло сначала прохладное,
а потом тёплое от драконьей спины. Выходные ещё не начались — их можно встретить с высоты.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("═" * 56)
    print(f"  {title}")
    print("═" * 56)


def main() -> None:
    dragon = Character(
        name="Гроктар",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий, с огоньком юмора",
        backstory=(
            "Древний страж знаний. В пятницу 2 октября "
            "встречает выходные над золотыми кронами. "
            "Седло всегда на месте. Иней на траве не страшен, если лететь вместе."
        ),
    )
    dragon.soul.add_habit("любит пятничные полёты", 0.5)
    dragon.soul.add_habit("встречает выходные из седла", 0.42)
    dragon.soul.add_habit("греет седло от инея", 0.46)
    dragon.soul.add_habit("любит октябрьский ветер", 0.36)
    dragon.soul.add_habit("считает золотые кроны с высоты", 0.34)
    dragon.soul.add_habit("греет всадника крылом", 0.6)
    dragon.soul.add_habit("любит утренние полёты", 0.48)

    print("🐉 Пятница, 2 октября, утро. Добрый дракон с седлом уже ждёт.")
    print("Второй день октября. На траве иней. Выходные ещё не начались — значит, их можно встретить с неба.")

    scene("1. У уступа")
    print(dragon.talk("Привет, всадник. Седло проверил, ремни мягкие. 2 октября — день, когда выходные кланяются с высоты."))
    dragon.soul.strengthen_habit("всегда проверяет седло", 0.07)
    dragon.soul.strengthen_habit("греет седло от инея", 0.12)
    dragon.soul.strengthen_habit("любит пятничные полёты", 0.16)
    dragon.soul.strengthen_habit("встречает выходные из седла", 0.2)
    dragon.soul.strengthen_habit("любит октябрьский ветер", 0.1)

    scene("2. Тёплое седло")
    print(dragon.talk("На траве иней, но спина уже греет седло. Садись: сначала прохладно, потом тепло."))
    dragon.soul.strengthen_habit("греет седло от инея", 0.1)
    dragon.soul.strengthen_habit("греет всадника крылом", 0.08)

    scene("3. Взлёт")
    print(dragon.talk("Держись крепче. Ветер пахнет яблоками и дымком далёких печей, а крыло уже тёплое."))
    dragon.soul.strengthen_habit("любит утренние полёты", 0.12)
    dragon.soul.strengthen_habit("любит октябрьский ветер", 0.1)

    scene("4. Золотые кроны")
    print(dragon.talk("Смотри: кроны ещё золотее, чем вчера. 2 октября осень не торопится — она просто красит лес."))
    dragon.soul.strengthen_habit("считает золотые кроны с высоты", 0.16)
    dragon.soul.strengthen_habit("любуется осенним светом", 0.1)

    scene("5. Крыло-плед")
    print(dragon.talk("Утро ещё свежее. Накрою крылом, как пледом. Выходные можно встретить и в тепле."))
    dragon.soul.strengthen_habit("греет всадника крылом", 0.12)

    scene("6. Почесывание на высоте")
    print(dragon.talk("Почеши за ухом. Пятница для этого тоже существует — особенно перед выходными."))
    dragon.soul.strengthen_habit("любит почесывания за ухом", 0.08)
    dragon.soul.strengthen_habit("рычит от удовольствия", 0.05)

    scene("7. Завтрак в облаках")
    print(dragon.talk("У меня есть тёплый хлеб и второе октябрьское яблоко. Делимся? Выходные начинаются с завтрака."))
    dragon.soul.strengthen_habit("делится утренним огоньком", 0.06)

    scene("8. Домой")
    print(dragon.talk("Спасибо за этот второй октябрь. Я рядом. Садись крепче — садимся домой, без спешки. Выходные уже машут крыльями."))

    print()
    print("═" * 56)
    print("Настроение:")
    print(dragon.mood())
    print()
    print("Привычки после пятничного октябрьского полёта:")
    print(dragon.habits())
    print()
    print("Душа:")
    print(dragon.describe_soul())
    print()
    print("Выходные уже в небе. Седло на месте. Лети со мной, всадник. 🔥")

    save_path = "groktar_friday_october_2.json"
    dragon.save(save_path)
    print(f"\nПрогресс сохранён в {save_path}")


if __name__ == "__main__":
    main()
