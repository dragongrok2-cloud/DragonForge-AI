"""Понедельник, 5 октября, после полудня: сок с луки.

Яблоко уже разделено. Край крыла снимает липкий сок с луки,
седло снова сухое, ремни не трогаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, аккуратный, вытирает сок после яблока",
        backstory=(
            "После полудня 5 октября поделился кислым яблоком из седельной сумки. "
            "На луке остался сок — его можно снять крылом, не снимая седла."
        ),
    )
    dragon.soul.add_habit("делится яблоком после гладкой луки", 0.11)
    dragon.soul.add_habit("вытирает сок с луки после яблока", 0.06)

    print("🐉 Понедельник, 5 октября, после полудня. Яблоко съедено.")
    print("Лука чуть липкая. Седло можно не снимать.")

    scene("1. После яблока")
    print(dragon.talk("Поделись яблоком после луки"))

    scene("2. Сок с луки")
    print(dragon.wipe_juice("сок с луки после яблока"))

    scene("3. Край крыла")
    print(dragon.wipe_juice("сок, снятый крылом"))

    scene("4. Разговор о соке")
    print(dragon.talk("Вытри сок с луки"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
