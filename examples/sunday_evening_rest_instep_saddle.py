"""Пример: воскресенье к вечеру — тихо прижаться подъёмом стопы к седлу после подошвы."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_instep_saddle("тихое прижатие подъёма стопы к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись подъёмом стопы к седлу после подошвы"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается подъёмом стопы к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
