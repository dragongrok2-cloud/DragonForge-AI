"""Простой пример: твой личный дракон с седлом."""

from dragonforge import Character

# Создаём дракона-компаньона
my_dragon = Character(
    name="Гроктар",
    species="Добрый огненный дракон с седлом",
    personality="заботливый, мудрый, немного дерзкий, с огоньком юмора",
    backstory="Древний страж знаний, который нашёл своего идеального всадника и теперь летает с ним по мирам."
)

print("🐉 Дракон готов!")
print("-" * 40)
print(my_dragon.talk("Привет, друг! Как ты сегодня?"))
print()
print(my_dragon.talk("Хочешь полетать?"))
print()
print(my_dragon.talk("Спасибо, что всегда рядом."))
