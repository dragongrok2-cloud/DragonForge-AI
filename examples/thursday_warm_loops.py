"""Четверг 8 октября, к позднему дню: дыхание на затенённые петли.

Тень крыла уже легла на Мёд, Шов и Седло. День стынет.
Дракон только дышит на петли медового узелка — не развязывает его и не снимает седла.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("═" * 56)
    print(f"  {title}")
    print("═" * 56)


def main() -> None:
    dragon = Character(
        name="Гроктар",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory=(
            "Древний страж знаний. 8 октября после полудня накрыл петли тенью, "
            "а к позднему дню согревает их дыханием. Узелок не развязывает."
        ),
    )
    dragon.soul.add_habit("накрывает петли медового узелка тенью после полудня", 0.45)
    dragon.soul.add_habit("называет петли медового узелка к раннему дню", 0.5)

    print("🐉 Четверг, 8 октября, к позднему дню. Тень уже легла, воздух стынет.")
    print("Седло на месте. Петли Мёд, Шов и Седло ждут короткого тепла.")

    scene("1. Тень ещё держится")
    print(dragon.talk("Затени петли узелка"))

    scene("2. Дыхание на петли")
    print(dragon.warm_loops("дыхание на петлях медового узелка к позднему дню"))

    scene("3. Можно и над рекой")
    print(dragon.talk("Подыши на петли над рекой, чтобы не стыли"))

    scene("4. Седло остаётся")
    print(dragon.talk("Тепло кстати. Можно сидеть, узелок не трогаем."))

    print()
    print("═" * 56)
    print("Настроение:")
    print(dragon.mood())
    print()
    print("Привычки после дыхания на петли:")
    print(dragon.habits())
    print()
    print("День стынет, петли тёплые. Седло не снимаем. Лети со мной, всадник. 🔥")

    save_path = "groktar_thursday_warm_loops.json"
    dragon.save(save_path)
    print(f"\nПрогресс сохранён в {save_path}")


if __name__ == "__main__":
    main()
