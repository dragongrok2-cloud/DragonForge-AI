"""Пример: воскресенье к вечеру — тихо прижаться пальцем лапы к седлу после лапы."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_toe_saddle("тихое прижатие пальца лапы к седлу под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Прижмись пальцем к седлу после лапы"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо прижимается пальцем лапы к седлу под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
