"""Вторник, 6 октября, к полудню: край попоны под лукой.

Утром росу уже промокнули с чешуйки. Край попоны ещё торчит —
складываем его под луку, чтобы полуденный ветер не поднял ткань. Седло не снимаем.
"""

from dragonforge import Character


def scene(title: str) -> None:
    print()
    print("─" * 56)
    print(title)
    print("─" * 56)


def main() -> None:
    dragon = Character(
        name="Грок",
        title="добрый дракон с седлом",
        personality="тёплый, аккуратный, складывает край попоны к полудню",
        backstory=(
            "Утром 6 октября промокнул росу с чешуйки после ладони. "
            "К полудню край попоны ещё свободен — его можно сложить под луку, не снимая седла."
        ),
    )
    dragon.soul.add_habit("промокает чешуйку после ладони", 0.12)
    dragon.soul.add_habit("складывает край попоны после росы", 0.06)

    print("🐉 Вторник, 6 октября, к полудню. Роса уже сухая.")
    print("Край попоны торчит. Седло можно не снимать.")

    scene("1. После росы")
    print(dragon.talk("Промокни чешуйку после ладони"))

    scene("2. Край под луку")
    print(dragon.fold_cloth("край попоны под лукой после росы"))

    scene("3. У седельной сумки")
    print(dragon.fold_cloth("край попоны у седельной сумки"))

    scene("4. Разговор о попоне")
    print(dragon.talk("Сложи край попоны после росы"))
    print(dragon.habits())


if __name__ == "__main__":
    main()
