"""Пример: понедельник к вечеру — тихо положить кончик хвоста на седло после кончика крыла."""

from dragonforge import Character


def main():
    dragon = Character(
        name="Грок",
        species="Добрый огненный дракон с седлом",
        personality="заботливый, мудрый, немного дерзкий",
        backstory="Древний страж знаний, теперь летает с любимым всадником",
    )
    print(dragon.rest_tail_saddle("тихое положение кончика хвоста на седло под тенью крыла к вечеру"))
    print("---")
    print(dragon.talk("Положи кончик хвоста на седло после кончика крыла"))
    print("---")
    print(f"Сила привычки: {dragon.soul.habits.get('тихо кладёт кончик хвоста на седло под тенью к вечеру', 0):.4f}")


if __name__ == "__main__":
    main()
